#!/usr/bin/env python3
"""Interleaved A/B timings and decoded-media equality on a generated 120s fixture.

Use the source.mp4 generated by source_views_benchmark.py. Source import is
excluded; cold means a new analysis recipe on a warm filesystem. No builds or
other renders should run concurrently. This is not a camera or model benchmark.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import statistics
import subprocess
import time


def digest(path):
    with Path(path).open('rb') as source:
        return hashlib.file_digest(source, 'sha256').hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('baseline', 'candidate', 'source', 'ffmpeg', 'ffprobe', 'output'):
        parser.add_argument('--' + name, required=True)
    parser.add_argument('--repetitions', type=int, default=5)
    args = parser.parse_args()
    assert 3 <= args.repetitions <= 10
    root = Path(args.output).resolve()
    root.mkdir(parents=True, exist_ok=False)
    source = Path(args.source).resolve()
    source_sha = digest(source)
    binaries = {'baseline': args.baseline, 'candidate': args.candidate}
    ledger = root / 'commands.jsonl'

    def run(argv, payload=None):
        result = subprocess.run(list(map(str, argv)), input=payload,
                                capture_output=True, timeout=300)
        assert result.returncode == 0, (argv, result.stdout[-2000:], result.stderr[-2000:])
        return result.stdout

    def call(label, command, **fields):
        request = {'command': command, 'project': str(root / label), **fields}
        result = json.loads(run([binaries[label], '--ffmpeg', args.ffmpeg,
                                 '--ffprobe', args.ffprobe, 'request', '-'],
                                json.dumps(request).encode()))
        with ledger.open('a') as log:
            log.write(json.dumps({'client': label, 'request': request,
                                  'ok': result['ok']}) + '\n')
        assert result['ok'], result
        return result['result']

    def decoded_hash(path):
        # Decode both streams independently of AVW, retaining the actual PTS.
        raw = run([args.ffmpeg, '-v', 'error', '-copyts', '-threads', '1',
                   '-i', path, '-map', '0:v:0', '-map', '0:a?',
                   '-c:v', 'rawvideo', '-threads:v', '1', '-c:a', 'pcm_s16le',
                   '-fps_mode', 'passthrough', '-enc_time_base:v', 'demux',
                   '-f', 'framehash', '-'])
        # Interleaving between streams is irrelevant; order within each is not.
        lines = sorted(raw.decode().splitlines(), key=lambda line: line.split(',')[0])
        return hashlib.sha256('\n'.join(lines).encode()).hexdigest()

    def worker_with_rss(label, log_path):
        # wait4 includes the worker's reaped media children. ru_maxrss is the
        # largest single process, not a sum of simultaneously resident pages.
        pid = os.fork()
        if pid == 0:
            try:
                with log_path.open('wb') as log:
                    os.dup2(log.fileno(), 1)
                    os.dup2(log.fileno(), 2)
                    os.execv(binaries[label], [binaries[label], 'worker', str(root / label)])
            finally:
                os._exit(127)
        _, status, usage = os.wait4(pid, 0)
        assert os.waitstatus_to_exitcode(status) == 0, log_path.read_text()[-2000:]
        return usage.ru_maxrss

    for label in binaries:
        call(label, 'create', name='Interleaved source-view performance')
        call(label, 'import', source=str(source), id='source',
             expectedRevision=0, key='benchmark-source-import')

    measurements, outputs = [], {}
    for repetition in range(args.repetitions):
        order = ['baseline', 'candidate'] if repetition % 2 == 0 else ['candidate', 'baseline']
        for kind in ('storyboard', 'preview'):
            request = ({'assetId': 'source', 'sampleEveryMs': 10000, 'limit': 12,
                        'maxBytes': 1048576 + repetition} if kind == 'storyboard' else
                       {'assetId': 'source', 'startMs': 15300, 'endMs': 25300,
                        'maxDurationMs': 10000, 'maxBytes': 1048576 + repetition,
                        'width': 640, 'height': 360})
            command = 'source-storyboard' if kind == 'storyboard' else 'budget-preview'
            for label in order:
                for phase in ('cold', 'cached'):
                    started = time.perf_counter()
                    job = call(label, command, request=request, expectedRevision=1,
                               key=f'{kind}-{phase}-{repetition}', noLaunch=True)
                    log_path = root / f'{label}-{kind}-{phase}-{repetition}.worker.log'
                    rss = worker_with_rss(label, log_path)
                    state = call(label, 'job-status', id=job['id'])
                    assert state['state'] == 'succeeded', state
                    artifact = call(label, 'artifact', id=job['id'])
                    elapsed = time.perf_counter() - started
                    assert state['result']['cacheHit'] == (phase == 'cached'), state
                    report = json.loads(Path(artifact['path']).read_text())['data']
                    file = Path(artifact['path']).parent / report['file']
                    if phase == 'cold':
                        if kind == 'storyboard':
                            assert [t['sourceTimeMs'] for t in report['tiles']] == list(range(0, 120000, 10000))
                            mapping = report['tiles']
                        else:
                            assert report['bytes'] <= request['maxBytes']
                            assert report['verification']['videoFrames'] == 300
                            mapping = report['frameMapping']
                        outputs[label, kind, repetition] = (mapping, decoded_hash(file))
                    measurements.append({'client': label, 'kind': kind, 'phase': phase,
                                         'repetition': repetition, 'seconds': elapsed,
                                         'peakWorkerOrChildRssKiB': rss,
                                         'bytes': report['bytes'],
                                         'encodingAttempts': report.get('attempts')})
                    print(label, kind, phase, repetition, round(elapsed, 4), flush=True)
            assert outputs['baseline', kind, repetition] == outputs['candidate', kind, repetition], kind

    assert digest(source) == source_sha
    medians = {}
    for label in binaries:
        medians[label] = {kind + '-' + phase: statistics.median(
            m['seconds'] for m in measurements
            if (m['client'], m['kind'], m['phase']) == (label, kind, phase))
            for kind in ('storyboard', 'preview') for phase in ('cold', 'cached')}
    summary = {'passed': True, 'sourceSha256': source_sha,
               'sourceBytes': source.stat().st_size, 'repetitions': args.repetitions,
               'decodedPixelsAudioAndTimestampsEqual': True,
               'originalUnchanged': True, 'medianSeconds': medians,
               'improvementPercent': {key: 100 * (1 - medians['candidate'][key] / value)
                                      for key, value in medians['baseline'].items()},
               'measurements': measurements,
               'binaries': {label: {'sha256': digest(binary),
                                    'version': run([binary, '--version']).decode().strip()}
                            for label, binary in binaries.items()},
               'platform': platform.platform(),
               'cpuQuota': Path('/sys/fs/cgroup/cpu.max').read_text().strip(),
               'memoryLimitBytes': Path('/sys/fs/cgroup/memory.max').read_text().strip(),
               'limits': ['Generated 120s 720p/30fps SDR fixture with B frames; warm filesystem.',
                          'Source generation/import and independent equality checks excluded from timings; enqueue, worker, integrity and artifact lookup included.',
                          'Interleaved clients; no concurrent build/render. No camera, 4K, ASR/model or hosted-agent performance inferred.']}
    (root / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n')
    print(json.dumps({'medianSeconds': medians, 'improvementPercent': summary['improvementPercent']}, indent=2))


if __name__ == '__main__':
    main()
